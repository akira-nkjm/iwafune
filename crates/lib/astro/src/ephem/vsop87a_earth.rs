//! VSOP87A（地球・直交座標・J2000 黄道と分点）の切り詰め系列。
//!
//! 係数は下の原典ファイルから切り詰めて書き出したもの（手で編集しない）。
//!
//! ## 出典
//!
//! Bretagnon P., Francou G., *Planetary theories in rectangular and spherical
//! variables: VSOP87 solution*, Astron. Astrophys. 202, 309 (1988)。
//! 原典ファイル: <https://cdsarc.cds.unistra.fr/ftp/VI/81/VSOP87A.ear>（CDS VizieR VI/81）。
//!
//! ## 何が入っているか
//!
//! 地球の**日心**直交座標 `(X, Y, Z)` [AU] を、J2000 からのユリウス千年 `T` の
//! 級数で与える:
//!
//! ```text
//!   X(T) = Σ_it T^it · Σ_n A·cos(B + C·T)
//! ```
//!
//! 座標系は **J2000 の力学的黄道と分点**。太陽の地心位置はこれを符号反転して
//! 得る（日心座標なので厳密に `−(地球の日心位置)`）。
//!
//! ## 切り詰め
//!
//! 原典 3538 項のうち **91 項**を採った。足切りは実効振幅
//! `A · T_max^it >= 1e-06 AU`（`T_max = 0.06` = ±60 年）で、
//! `T^it` の重みを織り込んだうえで 1e-6 AU（≒ 15 万 km ≒ 太陽方向で 0.2 秒角）を
//! 下回る項を落としている。打ち切り誤差の実測は [`crate::ephem`] の doc を参照。
//!
//! 内訳（座標ごとに `T^0 … T^5`）:
//!
//! | 座標 | T^0 | T^1 | T^2 | T^3 | T^4 | T^5 |
//! |---|---|---|---|---|---|---|
//! | X | 40 | 2 | 0 | 0 | 0 | 0 |
//! | Y | 42 | 2 | 0 | 0 | 0 | 0 |
//! | Z | 2 | 3 | 0 | 0 | 0 | 0 |

