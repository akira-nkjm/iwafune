//! 月の地心位置に使う Meeus（ELP2000-82B の要約）の周期項表。
//!
//! 係数は下の出典から機械的に転記したもの（手で編集しない）。
//!
//! ## 出典
//!
//! Jean Meeus, *Astronomical Algorithms*, 2nd ed., Willmann-Bell, 1998, Ch. 47
//! （表 47.A = 経度・距離 60 項、表 47.B = 緯度 60 項）。
//! 本文は ELP2000-82B（Chapront-Touzé & Chapront 1983）の要約。
//!
//! 書籍は機械可読でないので、IAU SOFA 派生の ERFA `moon98.c`（同じ表の実装、
//! BSD 3-clause）から機械転記した: <https://raw.githubusercontent.com/liberfa/erfa/master/src/moon98.c>。
//!
//! ## 何が入っているか
//!
//! 月の**その時点の平均黄道・分点**における黄経 λ・黄緯 β・地心距離 r を与える:
//!
//! ```text
//!   λ = L′ + (加算項 + Σ_n l_n·E^|M_n|·sin(D_n·D + M_n·M + M′_n·M′ + F_n·F)) [度]
//!   β =      (加算項 + Σ_n b_n·E^|M_n|·sin(同じ引数))                        [度]
//!   r = 385 000 560 +      Σ_n r_n·E^|M_n|·cos(同じ引数)                      `[m]`
//! ```
//!
//! `E` は地球軌道の離心率の永年変化を織り込む因子で、太陽の平均近点角 `M` を
//! 含む項にだけ `E^|M_n|` として掛かる（Meeus Ch.47 の指示どおり）。
//! 赤道系・J2000 への回し方は [`crate::ephem`] を参照。

