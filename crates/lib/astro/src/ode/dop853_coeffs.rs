/// 8 次解の重み `b_i`（`A[12]` の先頭 12 要素と同一）。
pub(crate) const B: [f64; N_STAGES] = {
    let mut b = [0.0; N_STAGES];
    let mut i = 0;
    while i < N_STAGES {
        b[i] = A[12][i];
        i += 1;
    }
    b
};

