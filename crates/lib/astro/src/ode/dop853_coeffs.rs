#[cfg(test)]
mod tests {
    use super::*;

    /// Butcher 行列の各行の総和は節点 `c_i` に一致する（Runge-Kutta の整合条件）。
    ///
    /// 係数表は人手で写す以上、写し間違いが最大のリスクになる。この整合条件は
    /// 1 要素の桁違いをほぼ確実に捕まえるので、出典照合に加えた機械的な検査として置く。
    #[test]
    fn butcher_rows_sum_to_nodes() {
        for (i, row) in A.iter().enumerate() {
            let sum: f64 = row.iter().sum();
            // 行 8〜11 は ±40 規模の項が打ち消し合って 0.6 前後になる。許容は
            // 「行の絶対値和 × 倍精度の相対精度」で与える（桁落ちの分だけ緩める）。
            let magnitude: f64 = row.iter().map(|a| a.abs()).sum();
            let tolerance = 16.0 * f64::EPSILON * magnitude.max(1.0);
            assert!(
                (sum - C[i]).abs() < tolerance,
                "row {i}: sum {sum} != c {} (tolerance {tolerance})",
                C[i]
            );
        }
    }

    /// 8 次解の重みの総和は 1（一次の整合条件）。
    #[test]
    fn weights_sum_to_one() {
        let sum: f64 = B.iter().sum();
        assert!((sum - 1.0).abs() < 1.0e-15, "sum(b) = {sum}");
    }

    /// 誤差推定係数はどちらも「2 つの整合した公式の差」なので総和は 0。
    #[test]
    fn error_weights_sum_to_zero() {
        let e3: f64 = E3.iter().sum();
        let e5: f64 = E5.iter().sum();
        assert!(e3.abs() < 1.0e-15, "sum(E3) = {e3}");
        assert!(e5.abs() < 1.0e-15, "sum(E5) = {e5}");
    }
}
