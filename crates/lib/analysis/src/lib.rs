//! # sat-analysis — 各系の解析
//!
//! すべての解析は [`spec::Analysis`] を実装し、`Input` → `Output` の純粋な関数として振る舞う。
//! 設計モデル（`fune-*`）を知らず、I/O もしない。入力の組み立ては呼び出し側（fune-projection）が行う。
//! 物理の共通部品（軌道・太陽・食・姿勢則・時系列・積分器）は `sat_astro` を使い、ここに書き直さない。
//!
//! | モジュール | 責務 |
//! |---|---|
//! | [`spec`] | 解析の共通の型（trait・情報・エラー・時系列とその種類・判定）、比の余裕の定義（`ratio_margin`）と判定文の数量の sat-units への委譲。時系列の集計（日照の判定・周回平均・時間の割合・最長の区間・期間不足の扱い）。表示名は持たない（service が語彙で引く） |
//! | [`catalog`] | 解析の一覧と、ID による動的な実行（ここだけで登録する） |
//! | [`modes`] | モードごとの状態・時間割合・稼働台と予備台の計算、部品の状態ごとの値の表（電源・C&DH・熱で共有） |
//! | [`power`] | 電源: モード別消費電力・日照時発電・軌道上発電・収支と DoD・逆算サイジング・噴射中の電力収支 |
//! | [`aocs`] | AOCS: 擾乱（推力誤差を含む）と RW アンロード（RCS の 1 日の推薬・ΔV 換算）・MTQ/RCS のアンロード時間・センサ FoV・姿勢変更の時間 |
//! | [`budget`] | バジェット（質量・電力・データ量）の集計と判定（判定はここだけ） |
//! | [`cdh`] | C&DH: HK・ミッションデータの量とストレージ |
//! | [`comm`] | 通信: 回線バジェット・可視・データ蓄積 |
//! | [`thermal`] | 熱: 多節点の定常・非定常 |
//! | [`orbit`] | 軌道条件: β と1周の本影・半影の季節変動、極値と蝕なし期間。大気抵抗による高度低下・軌道寿命・軌道維持の ΔV（太陽活動の条件ごと） |
//! | [`structure`] | 構造: 質量特性・準静的荷重・簡易固有振動数 |
//! | [`propulsion`] | 推進: マヌーバ（インパルス・有限燃焼・低推力・推力を入れた数値伝搬）・ΔV バジェット・推薬とタンク・スラスタの使い方・軌道の推移・推薬による質量特性の変化 |

